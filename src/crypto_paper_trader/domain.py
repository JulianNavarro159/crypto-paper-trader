from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum


class SignalType(str, Enum):
    """Discrete trading signal emitted by a market strategy."""

    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"


class OrderSide(str, Enum):
    """Execution side for a simulated or live market order."""

    BUY = "BUY"
    SELL = "SELL"


class ExitReason(str, Enum):
    """Reason explaining why an open position was closed."""

    STOP_LOSS = "STOP_LOSS"
    TAKE_PROFIT = "TAKE_PROFIT"
    SIGNAL_REVERSAL = "SIGNAL_REVERSAL"
    TRAILING_STOP = "TRAILING_STOP"


class MacroMarketRegime(str, Enum):
    """Broad cryptocurrency market trend condition derived from Bitcoin."""

    BULLISH = "BULLISH"
    NEUTRAL = "NEUTRAL"
    BEARISH = "BEARISH"


@dataclass(frozen=True)
class Candle:
    """Immutable OHLCV market candle representation.

    Args:
        symbol: Trading pair identifier such as SOLUSDT.
        open_time: Candle opening timestamp in UTC.
        close_time: Candle closing timestamp in UTC.
        open_price: First traded price during the interval.
        high_price: Highest traded price during the interval.
        low_price: Lowest traded price during the interval.
        close_price: Last traded price during the interval.
        volume: Base asset volume traded during the interval.
        is_closed: Flag indicating whether the candle interval has finalized.
    """

    symbol: str
    open_time: datetime
    close_time: datetime
    open_price: float
    high_price: float
    low_price: float
    close_price: float
    volume: float
    is_closed: bool


@dataclass(frozen=True)
class MarketSignal:
    """Actionable market evaluation output generated by the strategy layer.

    Args:
        symbol: Trading pair identifier.
        evaluated_at: UTC timestamp of the candle used for evaluation.
        signal_type: Discrete decision (BUY, SELL, or HOLD).
        reference_price: Current close price at evaluation time.
        stop_loss_price: Calculated protective stop loss price.
        take_profit_price: Calculated target take profit price.
        atr_value: Average True Range volatility indicator value.
        rsi_value: Relative Strength Index momentum value.
        fast_ema: Fast exponential moving average value.
        slow_ema: Slow exponential moving average value.
    """

    symbol: str
    evaluated_at: datetime
    signal_type: SignalType
    reference_price: float
    stop_loss_price: float
    take_profit_price: float
    atr_value: float
    rsi_value: float
    fast_ema: float
    slow_ema: float


@dataclass(frozen=True)
class Position:
    """Open paper trading position state.

    Args:
        position_id: Deterministic unique identifier for the position.
        symbol: Trading pair identifier.
        opened_at: UTC timestamp when the position was opened.
        entry_price: Execution price per unit of base asset.
        quantity: Base asset quantity held.
        notional_usdt: Gross quote amount allocated at entry.
        entry_fee_usdt: Trading fee paid in quote currency at entry.
        stop_loss_price: Protective stop loss trigger price.
        take_profit_price: Target take profit trigger price.
    """

    position_id: str
    symbol: str
    opened_at: datetime
    entry_price: float
    quantity: float
    notional_usdt: float
    entry_fee_usdt: float
    stop_loss_price: float
    take_profit_price: float
    peak_price: float = 0.0


@dataclass(frozen=True)
class TradeExecution:
    """Immutable record of an executed paper order.

    Args:
        client_order_id: Idempotency key uniquely identifying the execution.
        position_id: Identifier of the associated position.
        symbol: Trading pair identifier.
        side: Order direction (BUY or SELL).
        executed_at: UTC timestamp of execution.
        execution_price: Fill price per base unit.
        quantity: Filled base asset quantity.
        gross_notional_usdt: Total quote value before fees.
        fee_usdt: Exchange commission deducted in USDT.
        realized_pnl_usdt: Net profit or loss after entry and exit fees.
        reason: Reason for execution (SIGNAL_ENTRY or ExitReason value).
    """

    client_order_id: str
    position_id: str
    symbol: str
    side: OrderSide
    executed_at: datetime
    execution_price: float
    quantity: float
    gross_notional_usdt: float
    fee_usdt: float
    realized_pnl_usdt: float
    reason: str


@dataclass(frozen=True)
class PortfolioSnapshot:
    """Summary of paper trading account equity and performance metrics.

    Args:
        timestamp: UTC timestamp of the snapshot.
        available_cash_usdt: Uninvested USDT balance available for new orders.
        open_position_value_usdt: Mark-to-market value of active positions.
        total_equity_usdt: Sum of available cash and open position value.
        total_equity_cop: Estimated total equity converted to Colombian Pesos.
        realized_pnl_usdt: Cumulative realized net profit or loss in USDT.
        total_fees_paid_usdt: Cumulative exchange commissions paid in USDT.
        total_trades: Total count of executed orders.
    """

    timestamp: datetime
    available_cash_usdt: float
    open_position_value_usdt: float
    total_equity_usdt: float
    total_equity_cop: float
    realized_pnl_usdt: float
    total_fees_paid_usdt: float
    total_trades: int
